"""Категории расходов: автокатегоризация по ключевым словам + парсинг /add.

Чистые функции — легко тестируются без Telegram и БД.

Формат: /add 500 кофе
  - сумма — первое слово (можно с запятой: 500,50);
  - примечание — остаток строки;
  - категория — по ключевым словам в примечании, иначе «Разное».
"""
from __future__ import annotations

# Ключевые слова → категория (проверка подстроки, регистр не важен)
KEYWORDS: dict[str, list[str]] = {
    "Продукты": [
        "кофе", "обед", "ужин", "завтрак", "продукт", "еда", "магазин",
        "пятёрочка", "перекрёсток", "лента", "ашан", "овощи", "мясо",
    ],
    "Транспорт": [
        "такси", "метро", "бензин", "автобус", "трамвай", "троллейбус",
        "каршер", "парковка", "проезд",
    ],
    "Жильё": [
        "квартплат", "аренд", "коммунал", "ипотек", "жильё", "электричеств",
    ],
    "Связь и интернет": ["интернет", "телефон", "мобильн", "связь", "оператор", "тариф"],
    "Развлечения": [
        "кино", "игр", "концерт", "подписк", "театр", "фитнес", "спортзал", "развлечен",
    ],
    "Здоровье": ["аптек", "лекар", "врач", "здоров", "больниц", "витамин"],
    "Одежда": ["одежд", "куртк", "обув", "кроссовк", "футболк", "джинс"],
}

FALLBACK_CATEGORY = "Разное"


def categorize(note: str) -> str:
    """Определяет категорию по ключевым словам в примечании."""
    text = note.lower()
    for category, keys in KEYWORDS.items():
        if any(key in text for key in keys):
            return category
    return FALLBACK_CATEGORY


def parse_expense(text: str, max_amount: float = 1_000_000) -> tuple[float, str, str] | None:
    """'/add 500 кофе' → (500.0, 'кофе', 'Продукты'); None — если невалидно.

    text — аргументы команды без самого '/add' (например '500 кофе').
    """
    parts = text.strip().split(maxsplit=1)
    if not parts:
        return None
    try:
        amount = float(parts[0].replace(",", "."))
    except ValueError:
        return None
    if amount <= 0 or amount > max_amount:
        return None
    note = parts[1].strip() if len(parts) > 1 else ""
    return amount, note, categorize(note)
